  )
}

#* Perform Logistic regression
#* @post /logistic
function(req, res) {
  tryCatch({
    body <- parse_body(req)
    if (is.null(body)) {
      res$status <- 400
      return(list(error = "Invalid JSON body"))
    }

    # Load data (inline rows, or a file inside the uploads directory)
    data <- tryCatch(load_data(body[["data"]], body[["data_path"]]), error = function(e) e)
    if (inherits(data, "error")) {
      res$status <- 400
      return(list(error = conditionMessage(data)))
    }
    if (nrow(data) == 0) {
      res$status <- 400
      return(list(error = "The data has no rows"))
    }

    # Build a validated formula (never evaluates user-supplied code)
    model_formula <- tryCatch(resolve_formula(body, data), error = function(e) e)
    if (inherits(model_formula, "error")) {
      res$status <- 400
      return(list(error = conditionMessage(model_formula), available = names(data)))
    }
    formula_str <- formula_text(model_formula)
    dependent_var <- all.vars(model_formula)[1]

    # The outcome must have exactly two distinct (non-missing) values
    dep_values <- unique(stats::na.omit(data[[dependent_var]]))
    if (length(dep_values) != 2) {
      res$status <- 400
      return(list(
        error = "Dependent variable must have exactly two values for logistic regression",
        unique_values = as.character(utils::head(dep_values, 20))
      ))
    }

    # Encode as 0/1; report which value is modeled as the "success" (1)
    if (all(dep_values %in% c(0, 1))) {
      success_level <- "1"
    } else {
      levels_sorted <- sort(as.character(dep_values))
      success_level <- levels_sorted[2]
      data[[dependent_var]] <- ifelse(is.na(data[[dependent_var]]), NA,
                                      as.integer(as.character(data[[dependent_var]]) == success_level))
    }

    model <- suppressWarnings(
      glm(model_formula, data = data, family = binomial(link = "logit"),
          control = list(maxit = 100))
    )

    # Separation shows up as non-convergence or fitted probabilities of 0/1
    converged <- model$converged
    fitted_p <- stats::fitted(model)
    separation <- !converged || any(fitted_p < 1e-10 | fitted_p > 1 - 1e-10)
    convergence_warning <- NULL
    if (separation) {
      convergence_warning <- paste(
        "Possible complete or quasi-complete separation: some predictors perfectly",
        "predict the outcome. Coefficients and p-values may be unreliable."
      )
    }

    tidy_results <- tryCatch(
      suppressWarnings(tidy(model, conf.int = TRUE, exponentiate = FALSE)),
      error = function(e) suppressWarnings(tidy(model, conf.int = FALSE, exponentiate = FALSE))
    )
    if (!"conf.low" %in% names(tidy_results)) {
      tidy_results$conf.low <- NA
      tidy_results$conf.high <- NA
    }

    # Odds ratios and their confidence intervals
    tidy_results$odds_ratio <- exp(tidy_results$estimate)
    tidy_results$or_conf.low <- exp(tidy_results$conf.low)
    tidy_results$or_conf.high <- exp(tidy_results$conf.high)

    glance_results <- tryCatch(
      suppressWarnings(glance(model)),
      error = function(e) list(
        null.deviance = model$null.deviance,
        deviance = model$deviance,
        AIC = AIC(model),
        nobs = stats::nobs(model)
      )
    )

    r_code <- paste0(
      "# Logistic Regression Analysis\n",
      "# Generated by StatsMate\n\n",
      "library(broom)\n\n",
      "# Load your data\n",
      "data <- read.csv('your_data.csv')\n\n",
      "# Fit logistic model\n",
      "model <- glm(", formula_str, ", data = data, family = binomial(link = 'logit'))\n\n",
      "# View results (coefficients are on the log-odds scale)\n",
      "summary(model)\n",
      "tidy(model, conf.int = TRUE)\n",
      "glance(model)\n\n",
      "# Odds ratios with confidence intervals\n",
      "tidy(model, conf.int = TRUE, exponentiate = TRUE)\n"
    )

    result <- list(
      status = "success",
      model_type = "logistic",
      formula = formula_str,
      outcome_success_level = success_level,
      n_obs = stats::nobs(model),
      converged = converged,
      tidy = tidy_results,
      glance = glance_results,
      r_code = r_code,
      timestamp = format(Sys.time(), "%Y-%m-%d %H:%M:%S")
    )
    if (!is.null(convergence_warning)) result$warning <- convergence_warning
    result
  }, error = function(e) {
    res$status <- 500
    list(error = "Analysis failed", message = as.character(conditionMessage(e)))
  })
}

